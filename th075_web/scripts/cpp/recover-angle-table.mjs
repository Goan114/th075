// Recover the original immutable angle table for ordinary C++ lookup.
// Original instructions are executed only by the development comparison oracle.
import {writeFileSync,mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
import {oracle,root,sha,target} from '../../tests/cpp/helpers.mjs';
const m=await oracle();
try {
  m.call(0x41cae0,{limit:10000000});
  const bytes=Buffer.from(m.bytes(0x6884c0,3600*4));
  if(bytes.readFloatLE(0)!==1||Math.abs(bytes.readFloatLE(900*4))>1e-7)throw Error('Invalid original angle table');
  const words=Array.from({length:3600},(_,i)=>'0x'+bytes.readUInt32LE(i*4).toString(16).padStart(8,'0')+'u');
  const lines=[];for(let i=0;i<words.length;i+=8)lines.push('    '+words.slice(i,i+8).join(',')+',');
  writeFileSync(resolve(root,'cpp/game/AngleTable.inc'),'// Original TH075 1.11 cosine lookup: 3600 single-precision entries.\n// Generated by scripts/cpp/recover-angle-table.mjs; SHA256 '+sha(bytes)+'\n'+lines.join('\n')+'\n');
  mkdirSync(resolve(root,'artifacts/cpp/verification'),{recursive:true});
  const result={kind:'original-immutable-angle-data',target,initializer:'0x41cae0',table:'0x6884c0',entries:3600,sha256:sha(bytes),precisionControl:0x27f,completeGame:false};
  writeFileSync(resolve(root,'artifacts/cpp/verification/angle-table-data.json'),JSON.stringify(result,null,2)+'\n');
  console.log(JSON.stringify(result));
}finally {m.close();}
